#!/usr/bin/env python3
#
# Filename:         sv_lint.py
#
# File Description: House-style and rulebook linter for the SystemVerilog and
#                   Verilog sources: the RTL, the bound checkers and the
#                   testbenches. It checks the mechanical rules of
#                   docs/VERIFICATION_RULES.md and the project's coding
#                   standard - the ones a script can judge without opinion.
#                   Rules that need judgement (is a property complete, is it
#                   subsumed) are not here; RULES.md lists them.
#
#                   It only reports. Nothing is rewritten, and RTL findings
#                   are for the designer to act on.
#
#                   Usage: sv_lint.py [--report-only] [--rules R1,R2] [paths...]
#                     paths          files or folders (default: the RTL, sva/
#                                    and tb/ trees, tracked files only)
#                     --report-only  exit 0 even with errors
#                     --rules        run only these rules
#                   Exit status 1 if any error remains after exemptions.
#
#                   Every rule is one function named rule_<id>, documented in
#                   RULES.md under the same id. Accepted exceptions live in
#                   exemptions.txt beside this file, each with its reason.
#
#                   Standard library only. Comments and strings are blanked
#                   before a rule looks at code, so a keyword inside a comment
#                   or a message never counts.
#
# Global variables: DEFAULT_ROOTS, EXEMPTIONS_FILE, RULES - see below

