def _condition_end(src, n, col):

    """
    Purpose: Find where the parenthesised condition starting at line n,
             column col closes; returns (line, column after ')') or None.
    """
    depth, k, c = 0, n, col
    while k < len(src.code):
        line = src.code[k]
        while c < len(line):
            if line[c] == "(":
                depth += 1
            elif line[c] == ")":
                depth -= 1
                if depth == 0:
                    return k, c + 1
            c += 1
        k, c = k + 1, 0
    return None


def _next_code(src, n, col):

    """
    Purpose: The next code text after line n, column col: the rest of that
             line if it holds any, else the first non-empty code line after it.
             Returns (line index, text).
    """
    rest = src.code[n][col:].strip()
    if rest:
        return n, rest
    k = n + 1
    while k < len(src.code) and not src.code[k].strip():
        k += 1
    return k, (src.code[k].strip() if k < len(src.code) else "")


def rule_S1(src):

    """
    Purpose: An if or else whose statement sits on its own line uses begin /
             end. A one-line if / else (statement on the same line) needs
             none. else if chains are judged at the if.
    """
    for n, code in enumerate(src.code):
        for m in re.finditer(r"\b(if|else)\b", code):
            if m.group(1) == "if":
                paren = code.find("(", m.end())
                if paren < 0:
                    continue
                end = _condition_end(src, n, paren)
                if end is None:
                    continue
                k, text = _next_code(src, end[0], end[1])
                same_line = k == end[0] and src.code[end[0]][end[1]:].strip()
            else:
                k, text = _next_code(src, n, m.end())
                if re.match(r"if\b", text):
                    continue
                same_line = k == n
            if re.match(r"begin\b", text):
                continue
            if same_line:
                continue          # one-line if / else
            yield n + 1, f"multi-line '{m.group(1)}' without begin / end"


def _is_one_line_block(code):
    """Purpose: begin and its end on the same line."""
    return re.search(r"\bbegin\b.*\bend\b", code) is not None


def rule_S2(src):

    """
    Purpose: A blank line after every line that opens a block: a multi-line
             begin, a module header, a task / function / property / sequence
             declaration. If the block starts with a Purpose block, a blank
             line follows that too. A comment line is not a blank line.
    """
    for n, what in _opener_lines(src):
        if not is_blank(src, n + 1):
            yield n + 1, f"no blank line after {what}"
            continue
        after = block_comment_after(src, n)
        if after and "Purpose" in comment_text(src, after) and not is_blank(src, after[1] + 1):
            yield after[1] + 2, "no blank line after the Purpose block"


def rule_S3(src):

    """
    Purpose: A blank line before every line that closes a block: end,
             endmodule, endtask, endfunction, endproperty, endsequence. A
             comment line is not a blank line.
    """
    for n, code in enumerate(src.code):
        m = re.match(r"\s*(end(?!\w)|endmodule|endtask|endfunction|endproperty|endsequence)\b", code)
        if not m or _is_one_line_block(code):
            continue
        if m.group(1) != "end" and re.search(rf"\b({SUBROUTINE_OPENERS}|property|sequence)\b", code):
            continue                        # opened and closed on one line
        if not is_blank(src, n - 1):
            yield n + 1, f"no blank line before {m.group(1)}"


def rule_S4(src):

    """
    Purpose: The module body sits at the same indentation as module /
             endmodule: lines directly inside a module (not inside its
             blocks) start in column 0. Reported once per module, at the first
             offending line.
    """
    depth, in_module, header_done, reported = 0, False, False, False
    for n, code in enumerate(src.code):
        s = code.strip()
        if re.match(r"module\b", s):
            in_module, header_done, reported, depth = True, False, False, 0
        if not in_module:
            continue
        if not header_done:
            if re.search(r"\)\s*;\s*$", code) or re.match(r"module\s+\w+\s*;", s):
                header_done = True
            continue
        if re.match(r"endmodule\b", s):
            in_module = False
            continue
        if s and depth == 0 and code[:1] in (" ", "\t") and not reported:
            yield n + 1, "module body is indented; it sits at the indentation of module / endmodule"
            reported = True
        depth += len(re.findall(r"\b(begin|fork|case[xz]?|function|task|property|sequence|generate|covergroup)\b", code))
        depth -= len(re.findall(r"\b(end|join|join_any|join_none|endcase|endfunction|endtask|endproperty|endsequence|endgenerate|endgroup)\b", code))
        depth = max(depth, 0)


