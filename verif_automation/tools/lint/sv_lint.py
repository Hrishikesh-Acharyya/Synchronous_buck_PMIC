@dataclass
class Source:

    """
    Purpose: One file as the rules see it: the raw lines (comments and strings
             intact, for header and message rules) and the code lines (same
             line count, comments and string contents blanked to spaces, for
             every rule that looks at code).
    """

    path: pathlib.Path
    rel: str
    raw: list = field(default_factory=list)
    code: list = field(default_factory=list)
    comment_lines: set = field(default_factory=set)

    @property
    def kind(self):
        """Purpose: rtl, sva or tb, from the tree the file sits in."""
        top = self.rel.split("/", 1)[0]
        return {"rtl-systemverilog": "rtl", "sva": "sva", "tb": "tb"}.get(top, "other")

    @property
    def is_checker(self):
        """Purpose: a bound checker module (not the package or the bind file)."""
        return self.kind == "sva" and self.path.name.endswith("_sva.sv")


def load(path, rel):

    """
    Purpose: Read a file and blank its comments and string contents, keeping
             every newline so line numbers stay true. Lines that are entirely
             comment are remembered (for the spacing rules, a comment line is
             not a blank line).
    """
    text = path.read_bytes().decode("utf-8", "replace").replace("\r", "")
    out, i, state = [], 0, "code"
    comment_chars = set()
    while i < len(text):
        c, nxt = text[i], text[i + 1] if i + 1 < len(text) else ""
        if state == "code":
            if c == "/" and nxt == "/":
                state = "line"; out.append("  "); comment_chars.update((i, i + 1)); i += 2; continue
            if c == "/" and nxt == "*":
                state = "block"; out.append("  "); comment_chars.update((i, i + 1)); i += 2; continue
            if c == '"':
                state = "string"; out.append('"'); i += 1; continue
            out.append(c); i += 1; continue
        if state == "line":
            if c == "\n":
                state = "code"; out.append("\n")
            else:
                out.append(" "); comment_chars.add(i)
            i += 1; continue
        if state == "block":
            if c == "*" and nxt == "/":
                state = "code"; out.append("  "); comment_chars.update((i, i + 1)); i += 2; continue
            out.append("\n" if c == "\n" else " ")
            if c != "\n":
                comment_chars.add(i)
            i += 1; continue
        if state == "string":
            if c == "\\" and nxt:
                out.append("  "); i += 2; continue
            if c == '"':
                state = "code"; out.append('"'); i += 1; continue
            out.append("\n" if c == "\n" else " "); i += 1; continue
    src = Source(path=path, rel=rel, raw=text.split("\n"), code="".join(out).split("\n"))
    # a line is a comment line if it has no code but is not blank
    for n, (raw, code) in enumerate(zip(src.raw, src.code)):
        if raw.strip() and not code.strip():
            src.comment_lines.add(n)
    return src


@dataclass
class Finding:

    """
    Purpose: One reported problem: the rule, its level (error / warning), the
             file and 1-based line, and what is wrong.
    """

    rule: str
    level: str
    rel: str
    line: int
    message: str


def is_blank(src, n):
    """Purpose: line n (0-based) is empty or whitespace only."""
    return 0 <= n < len(src.raw) and not src.raw[n].strip()


def block_comment_after(src, n):

    """
    Purpose: If the first non-blank line after line n opens a /* block, return
             (first, last) 0-based lines of that block; otherwise None.
    """
    k = n + 1
    while k < len(src.raw) and not src.raw[k].strip():
        k += 1
    if k >= len(src.raw) or not src.raw[k].lstrip().startswith("/*"):
        return None
    last = k
    while last < len(src.raw) and "*/" not in src.raw[last]:
        last += 1
    return k, last


def block_comment_before(src, n):

    """
    Purpose: If the last non-blank line before line n closes a /* block,
             return (first, last) 0-based lines of that block; otherwise None.
    """
    k = n - 1
    while k >= 0 and not src.raw[k].strip():
        k -= 1
    if k < 0 or "*/" not in src.raw[k]:
        return None
    first = k
    while first >= 0 and "/*" not in src.raw[first]:
        first -= 1
    return (first, k) if first >= 0 else None


def comment_text(src, span):
    """Purpose: the raw text of a comment span (first, last)."""
    return "\n".join(src.raw[span[0]:span[1] + 1])


# ==============================================================================
# Rules - file header and ending
# ==============================================================================

def rule_H1(src):

    """
    Purpose: The file opens with the header block, and it carries the three
             lines # Filename:, # File Description: and # Global variables:.
             Presence only: what Global variables lists is not checked.
    """
    first = next((n for n, l in enumerate(src.raw) if l.strip()), None)
    if first is None or not src.raw[first].lstrip().startswith("/*") and not src.raw[first].lstrip().startswith("//"):
        yield 1, "no header block at the top of the file"
        return
    header = "\n".join(src.raw[first:first + 120])
    for key in ("Filename:", "File Description:", "Global variables:"):
        if not re.search(r"^\s*(?://\s*)?#\s*" + re.escape(key), header, re.M):
            yield first + 1, f"header has no '# {key}' line"


def rule_H2(src):

    """
    Purpose: The header's Filename names this file.
    """
    for n, line in enumerate(src.raw[:60]):
        m = re.search(r"#\s*Filename:\s*(\S+)", line)
        if m:
            if m.group(1) != src.path.name:
                yield n + 1, f"header says Filename: {m.group(1)}, the file is {src.path.name}"
            return


def rule_H3(src):

    """
    Purpose: The file ends with `default_nettype wire, so the next file
             compiled starts from the default.
    """
    tail = [l.strip() for l in src.raw if l.strip()]
    if not tail or tail[-1] != "`default_nettype wire":
        yield len(src.raw), "file does not end with `default_nettype wire"


def _block_opener(src, n):

    """
    Purpose: If line n starts an always / initial / final / task / function
             block that spans more than one line, return the 0-based line its
             declaration ends on (the line holding begin, or the task /
             function header's closing ';'). Return None for any other line,
             and for a single-statement always / initial with no begin.
    """
    code = src.code[n]
    if re.match(rf"\s*({PROCEDURAL_OPENERS})\b", code):
        if re.search(r"\bbegin\b", code):
            return None if _is_one_line_block(code) else n
        if code.rstrip().endswith(";"):
            return None
        k = n + 1
        while k < len(src.code) and not src.code[k].strip():
            k += 1
        if k < len(src.code) and re.match(r"\s*begin\b", src.code[k]):
            return k
        return None
    if re.match(rf"\s*({SUBROUTINE_OPENERS})\b", code):
        k = n
        while k < len(src.code) and ";" not in src.code[k]:
            k += 1
        if k < len(src.code) and re.search(r"\bend(task|function)\b", src.code[k]):
            return None                     # the whole subroutine on one line
        return k if k < len(src.code) else None
    return None


def _opener_lines(src):

    """
    Purpose: Every line that opens a block, 0-based: a multi-line begin, the
             line that closes a module header, and the line that ends a
             task / function / property / sequence declaration.
    """
    for n, code in enumerate(src.code):
        if re.search(r"\bbegin\b(\s*:\s*\w+)?\s*$", code) and not _is_one_line_block(code):
            yield n, "begin"
        elif re.match(r"\s*module\b", code):
            k = n
            while k < len(src.code) and not re.search(r"\)\s*;|^\s*module\s+\w+\s*;", src.code[k]):
                k += 1
            if k < len(src.code):
                yield k, "the module header"
        elif re.match(rf"\s*({SUBROUTINE_OPENERS}|property|sequence)\b", code):
            k = n
            while k < len(src.code) and ";" not in src.code[k]:
                k += 1
            if k < len(src.code) and not re.search(r"\bend(task|function|property|sequence)\b", src.code[k]):
                kind = re.search(r"\b(task|function|property|sequence)\b", code).group(1)
                yield k, f"the {kind} declaration"


