def rule_B1(sources):

    """
    Purpose: Every checker module is bound in sva/bind_sva.sv, and every bind
             names a checker that exists.
    """
    bind = next((s for s in sources if s.rel == "sva/bind_sva.sv"), None)
    checkers = {}
    for s in sources:
        if s.is_checker:
            for code in s.code:
                m = re.match(r"\s*module\s+(\w+)", code)
                if m:
                    checkers[m.group(1)] = s
    if bind is None:
        return
    bound = {}
    for n, code in enumerate(bind.code):
        m = re.match(r"\s*bind\s+\w+\s+(\w+)", code)
        if m:
            bound[m.group(1)] = n
    for name, s in checkers.items():
        if name not in bound:
            yield s, 1, f"checker {name} is not bound in sva/bind_sva.sv"
    for name, n in bound.items():
        if name not in checkers:
            yield bind, n + 1, f"bind names {name}, which no checker file defines"


