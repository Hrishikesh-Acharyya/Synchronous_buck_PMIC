def _labels(src, kind):

    """
    Purpose: Every 'label: assert/cover property' in the checker, as
             {label: line index}, plus unlabelled ones as a list of lines.
    """
    text = "\n".join(src.code)
    labelled, unlabelled = {}, []
    for m in re.finditer(rf"\b{kind}\s+property\b", text):
        line = text.count("\n", 0, m.start())
        before = text[:m.start()].rstrip()
        lm = re.search(r"(\w+)\s*:\s*$", before)
        if lm:
            labelled[lm.group(1)] = line
        else:
            unlabelled.append(line)
    return labelled, unlabelled


def rule_N1(src):

    """
    Purpose: Checker names follow the scheme: every assertion is labelled a_,
             every cover c_, every named property p_.
    """
    if not src.is_checker:
        return
    for kind, prefix in (("assert", "a_"), ("cover", "c_")):
        labelled, unlabelled = _labels(src, kind)
        for line in unlabelled:
            yield line + 1, f"{kind} property without a label"
        for label, line in labelled.items():
            if not label.startswith(prefix):
                yield line + 1, f"{kind} label {label} does not start with {prefix}"
    for n, code in enumerate(src.code):
        m = re.match(r"\s*property\s+(\w+)", code)
        if m and not m.group(1).startswith("p_"):
            yield n + 1, f"property {m.group(1)} does not start with p_"


def rule_N2(src):

    """
    Purpose: Every named property is asserted or covered somewhere (a property
             nobody uses checks nothing), and an assertion that uses a named
             property shares its stem (a_X asserts p_X).
    """
    if not src.is_checker:
        return
    text = "\n".join(src.code)
    for n, code in enumerate(src.code):
        m = re.match(r"\s*property\s+(p_\w+)", code)
        if m and not re.search(rf"property\s*\(\s*{m.group(1)}\s*\)", text):
            yield n + 1, f"property {m.group(1)} is never asserted or covered"
    for m in re.finditer(r"\b(a_\w+)\s*:\s*assert\s+property\s*\(\s*(p_\w+)\s*\)", text):
        if m.group(1)[2:] != m.group(2)[2:]:
            line = text.count("\n", 0, m.start())
            yield line + 1, f"{m.group(1)} asserts {m.group(2)} - the stems differ"


def _groups(src):

    """
    Purpose: The checker's PAC groups: the stretches of lines between the
             //////// rule lines that separate them. Returns (first, last)
             0-based line ranges; one range covering the file if it has none.
    """
    rules = [n for n, l in enumerate(src.raw) if re.match(r"\s*/{16,}\s*$", l)]
    edges = [0] + rules + [len(src.raw)]
    return [(edges[i], edges[i + 1]) for i in range(len(edges) - 1)]


def rule_N3(src):

    """
    Purpose: Every assertion has a cover in its own PAC group - the group
             being the lines between two //////// rule lines. Stems need not
             match (a group's covers are named for what they show), and
             cover-only groups are fine. A file without rule lines is judged
             by name instead: a cover c_X or c_X_..., or one its Purpose block
             names as shared.
    """
    if not src.is_checker:
        return
    asserts, _ = _labels(src, "assert")
    covers, _ = _labels(src, "cover")
    groups = _groups(src)
    if len(groups) > 1:
        for label, line in asserts.items():
            first, last = next(g for g in groups if g[0] <= line < g[1])
            if any(first <= c < last for c in covers.values()):
                continue
            # a documented decision (rulebook 6): the group's Purpose says
            # it shares another group's cover, or why it has none
            group = "\n".join(src.raw[first:last])
            start = group.find("Purpose")
            purpose = group[start:].split("*/", 1)[0] if start >= 0 else ""
            if re.search(r"(?i)\bno covers?\b|\bno cover of its own\b|\bshares?\b[^.]*\bcover|\bcover[^.]*\bshared\b", purpose):
                continue
            if set(re.findall(r"\bc_\w+", purpose)) & set(covers):
                continue
            yield line + 1, f"{label}'s PAC group has no cover, and its Purpose block does not say it shares one"
        return
    covers, _ = _labels(src, "cover")
    for label, line in asserts.items():
        if not label.startswith("a_"):
            continue
        stem = label[2:]
        if any(c == "c_" + stem or c.startswith("c_" + stem + "_") for c in covers):
            continue
        # the Purpose block of the group: the nearest block comment above the property or assertion
        prop_line = next((n for n, c in enumerate(src.code) if re.match(rf"\s*property\s+p_{stem}\b", c)), line)
        span = block_comment_before(src, prop_line)
        named = set(re.findall(r"\bc_\w+", comment_text(src, span))) if span else set()
        if named & set(covers):
            continue
        yield line + 1, f"{label} has no cover: no c_{stem}, and its Purpose block names no existing cover it shares"


def _action_text(src, label, line):

    """
    Purpose: The raw text of an assertion's action block: from its label to
             the next PAC group's label or rule line.
    """
    end = line + 1
    while end < len(src.raw) and not re.match(r"\s*(a_|c_|p_|property\b|/\*)", src.raw[end]):
        end += 1
    return "\n".join(src.raw[line:end])


def rule_N4(src):

    """
    Purpose: An assertion reports through sva_pkg::note_failure(), with a
             message that starts with its own label.
    """
    if not src.is_checker:
        return
    asserts, _ = _labels(src, "assert")
    for label, line in asserts.items():
        action = _action_text(src, label, line)
        if "note_failure" not in action:
            yield line + 1, f"{label} does not report through sva_pkg::note_failure()"
            continue
        msg = re.search(r'"([^"]*)', action)
        if msg and not msg.group(1).startswith(label):
            yield line + 1, f"{label}'s failure message does not start with its label"


def rule_N5(src):

    """
    Purpose: No $error or $fatal in a checker, and no $fatal in a testbench:
             $error ends a Verilator run at the first failure, and $fatal
             bypasses the failure tally.
    """
    for n, code in enumerate(src.code):
        if src.kind == "sva" and re.search(r"\$(error|fatal)\b", code):
            yield n + 1, "$error / $fatal in a checker - report through sva_pkg::note_failure()"
        elif src.kind == "tb" and re.search(r"\$fatal\b", code):
            yield n + 1, "$fatal in a testbench - finish_run() is the single exit"


def _properties(src):

    """
    Purpose: Every named property: (name, first line, code text of its body).
    """
    for n, code in enumerate(src.code):
        m = re.match(r"\s*property\s+(\w+)", code)
        if m:
            k = n
            while k < len(src.code) and not re.match(r"\s*endproperty\b", src.code[k]):
                k += 1
            yield m.group(1), n, "\n".join(src.code[n:k])


def rule_P1(src):

    """
    Purpose: A property about reset - its antecedent tests !rst_n - carries no
             disable iff, which would silence it exactly when it applies.
    """
    if src.kind != "sva":
        return
    for name, n, body in _properties(src):
        head = re.split(r"\|->|\|=>", body, maxsplit=1)[0]
        head = re.sub(r"disable\s+iff\s*\([^)]*\)", "", head)
        if re.search(r"(!|~)\s*rst_n\b", head) and re.search(r"disable\s+iff", body):
            yield n + 1, f"{name} is about reset (antecedent tests !rst_n) but has disable iff"


def rule_P2(src):

    """
    Purpose: == in properties; === and !== belong only in a testbench's
             procedural check().
    """
    if src.kind != "sva":
        return
    for n, code in enumerate(src.code):
        if re.search(r"===|!==", code):
            yield n + 1, "=== / !== in a checker - use =="


def _widths(src):

    """
    Purpose: Which names in the file are declared multi-bit: a packed range
             other than [0:0], or a named type (an enum such as state_t, int).
             Returns {name: True if multi-bit}; names declared any other way
             are absent and not judged.
    """
    widths = {}
    decl = re.compile(r"^\s*(?:(?:input|output|inout)\s+)?(?:(?:wire|var)\s+)?"
                      r"(logic|bit|reg|wire|int|integer|[A-Za-z_]\w*_t)\b\s*(\[[^\]]+\])?\s*"
                      r"([A-Za-z_]\w*(?:\s*,\s*[A-Za-z_]\w*)*)\s*[;,)=]")
    for code in src.code:
        for m in decl.finditer(code):
            typ, rng, names = m.group(1), m.group(2), m.group(3)
            multi = (typ in ("int", "integer") or typ.endswith("_t")
                     or (rng is not None and re.sub(r"\s", "", rng) != "[0:0]"))
            for name in re.split(r"\s*,\s*", names):
                widths[name] = multi
    return widths


def rule_P3(src):

    """
    Purpose: $rose / $fell test bit 0 only; on a multi-bit signal use
             $changed. Judged where the argument is a plain name declared in
             the same file.
    """
    if src.kind != "sva":
        return
    widths = _widths(src)
    for n, code in enumerate(src.code):
        for m in re.finditer(r"\$(rose|fell)\s*\(\s*([A-Za-z_]\w*)\s*\)", code):
            if widths.get(m.group(2)):
                yield n + 1, f"${m.group(1)}({m.group(2)}) on a multi-bit signal tests bit 0 only - use $changed"


def _reset_helpers(src):

    """
    Purpose: The out-of-reset helpers a file declares: checker-local signals
             named for reset (out_of_reset, clocks_after_reset_release),
             which hold a property off until the first edges after reset.
    """
    text = "\n".join(src.code)
    names = set(re.findall(r"\b(?:logic|bit|int|reg)\b[^;]*?\b(\w*reset\w*)\s*[;,=\[]", text))
    return {n for n in names if n not in ("rst_n",)}


def rule_P4(src):

    """
    Purpose: A property that reaches back one edge ($past, $stable, $changed,
             |=>) is guarded against a mid-cycle reset: it reads $past(rst_n)
             or an out-of-reset helper. A property about reset itself (its
             antecedent tests !rst_n) needs no guard.
    """
    if not src.is_checker:
        return
    helpers = _reset_helpers(src)
    for name, n, body in _properties(src):
        if not re.search(r"\$past\s*\(|\$stable\s*\(|\$changed\s*\(|\|=>", body):
            continue
        head = re.split(r"\|->|\|=>", body, maxsplit=1)[0]
        if re.search(r"(!|~)\s*rst_n\b", re.sub(r"disable\s+iff\s*\([^)]*\)", "", head)):
            continue
        if re.search(r"\$past\s*\(\s*rst_n\b", body) or any(re.search(rf"\b{h}\b", body) for h in helpers):
            continue
        yield n + 1, f"{name} reaches back one edge but is not guarded by $past(rst_n) or an out-of-reset helper"


