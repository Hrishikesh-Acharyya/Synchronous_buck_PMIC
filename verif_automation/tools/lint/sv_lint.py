def rule_K1(src):

    """
    Purpose: Parameters and localparams are ALL CAPS.
    """
    for n, code in enumerate(src.code):
        for m in re.finditer(r"\b(parameter|localparam)\b([^=;]*?)\b([A-Za-z_]\w*)\s*=", code):
            name = m.group(3)
            if name != name.upper():
                yield n + 1, f"{m.group(1)} {name} is not ALL CAPS"


