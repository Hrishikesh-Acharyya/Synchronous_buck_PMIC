# RULES: id -> (level, function, description). File rules take one Source;
#        B-rules take every source.
RULES = {
    "H1": ("error",   rule_H1, "header block with Filename / File Description / Global variables lines"),
    "H2": ("error",   rule_H2, "header Filename matches the file"),
    "H3": ("error",   rule_H3, "file ends with `default_nettype wire"),
    "C1": ("error",   rule_C1, "every always / initial block, task and function has a Purpose block, inside it"),
    "S1": ("error",   rule_S1, "multi-line if / else use begin / end"),
    "S2": ("error",   rule_S2, "blank line after every block opener, and after a block's Purpose block"),
    "S3": ("error",   rule_S3, "blank line before every block closer"),
    "S4": ("warning", rule_S4, "module body at the indentation of module / endmodule"),
    "K1": ("error",   rule_K1, "parameters and localparams in ALL CAPS"),
    "N1": ("error",   rule_N1, "a_ / c_ / p_ naming in checkers"),
    "N2": ("error",   rule_N2, "every property used; a_X asserts p_X"),
    "N3": ("error",   rule_N3, "every assertion has a cover (same stem, or named as shared)"),
    "N4": ("error",   rule_N4, "assertions report through note_failure() with a label-first message"),
    "N5": ("error",   rule_N5, "no $error / $fatal in checkers, no $fatal in testbenches"),
    "P1": ("error",   rule_P1, "a property about reset has no disable iff"),
    "P2": ("error",   rule_P2, "no === / !== in checkers"),
    "P3": ("error",   rule_P3, "no $rose / $fell on multi-bit signals"),
    "P4": ("error",   rule_P4, "a property reaching back one edge is guarded by $past(rst_n) or an out-of-reset helper"),
    "B1": ("error",   rule_B1, "every checker bound, every bind's checker exists"),
}
CROSS_FILE_RULES = {"B1"}


def load_exemptions():

    """
    Purpose: The accepted exceptions: (rule, path glob, reason) per line;
             '#' starts a comment. A line without a reason is itself an error.
    """
    exemptions = []
    if not EXEMPTIONS_FILE.exists():
        return exemptions
    for n, line in enumerate(EXEMPTIONS_FILE.read_text().splitlines(), 1):
        line = line.split("#", 1)[0].rstrip() if not line.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        parts = re.split(r"\t+|\s{2,}", line.strip(), maxsplit=2)
        if len(parts) < 3:
            sys.exit(f"{EXEMPTIONS_FILE.name}:{n}: an exemption needs RULE, path glob and a reason")
        exemptions.append(tuple(parts))
    return exemptions


def collect(paths, repo):

    """
    Purpose: The .sv / .v files to lint: the tracked files under the given
             paths (default the RTL, sva/ and tb/ trees).
    """
    roots = paths or DEFAULT_ROOTS
    tracked = subprocess.run(["git", "ls-files", "--", *roots], cwd=repo, capture_output=True,
                             text=True).stdout.split()
    if not tracked:     # not a git checkout, or untracked files named directly
        tracked = [str(p.relative_to(repo)) for r in roots for p in
                   ([repo / r] if (repo / r).is_file() else (repo / r).rglob("*"))]
    return sorted(f for f in tracked if f.endswith((".sv", ".v")))


def main():

    """
    Purpose: Lint, apply the exemptions, print the findings and a per-rule
             summary, and set the exit status.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("paths", nargs="*")
    parser.add_argument("--report-only", action="store_true")
    parser.add_argument("--rules")
    args = parser.parse_args()
    repo = pathlib.Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                                       text=True).stdout.strip() or ".")
    wanted = set(args.rules.split(",")) if args.rules else set(RULES)

    # header: the date and commit, so a saved report stands as evidence
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=repo, capture_output=True,
                            text=True).stdout.strip() or "unknown"
    dirty = subprocess.run(["git", "status", "--porcelain", "--", *(args.paths or DEFAULT_ROOTS)],
                           cwd=repo, capture_output=True, text=True).stdout.strip()
    print(f"sv_lint report - {datetime.date.today().isoformat()} - commit {commit}"
          + (" (linted files have uncommitted changes)" if dirty else ""))
    print(f"scope: {' '.join(args.paths or DEFAULT_ROOTS)}\n")

    sources = [load(repo / rel, rel) for rel in collect(args.paths, repo)]
    findings = []
    for rule_id, (level, fn, _) in RULES.items():
        if rule_id not in wanted:
            continue
        if rule_id in CROSS_FILE_RULES:
            for src, line, msg in fn(sources):
                findings.append(Finding(rule_id, level, src.rel, line, msg))
        else:
            for src in sources:
                for line, msg in fn(src):
                    findings.append(Finding(rule_id, level, src.rel, line, msg))

    exemptions = load_exemptions()
    kept, exempted = [], []
    for f in findings:
        (exempted if any(f.rule == r and fnmatch.fnmatch(f.rel, g) for r, g, _ in exemptions)
         else kept).append(f)

    for f in sorted(kept, key=lambda f: (f.rel, f.line, f.rule)):
        print(f"{f.rel}:{f.line}: {f.level} {f.rule}: {f.message}")
    errors = sum(f.level == "error" for f in kept)
    warnings = len(kept) - errors
    print(f"\nsv_lint: {len(sources)} files - {errors} errors, {warnings} warnings, {len(exempted)} exempted")
    print(f"  {'rule':<5}{'level':<9}{'found':>6}  description")
    for rule_id, (level, _, desc) in RULES.items():
        if rule_id in wanted:
            count = sum(f.rule == rule_id for f in kept)
            print(f"  {rule_id:<5}{level:<9}{count:>6}  {desc}")
    sys.exit(1 if errors and not args.report_only else 0)


if __name__ == "__main__":
    main()
