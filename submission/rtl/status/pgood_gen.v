/*

# Filename:         pgood_gen.v

# File Description: Power-good indicator. Asserts PGOOD once the output
#                    comparator has reported a good rail continuously for a
#                    qualifying period while the supervisor is regulating,
#                    and drops it immediately when either condition fails.
#                    PGOOD drives the changeover that moves the secondary
#                    analog circuitry off the input LDO and onto the
#                    converter's own output, so assertion is deliberately
#                    slow and deassertion deliberately immediate: a load must
#                    be handed back to the LDO before the rail collapses,
#                    not after.

#                   Verilog-2005, converted from rtl/status/pgood_gen.sv by sv2v,
#                   with the comments restored by hand from the source.

# Global variables: None

*/
`timescale 1ns/1ps
`default_nettype none
module pgood_gen (
	clk,
	rst_n,
	pwm_sync,
	pgood_comp,
	run_active,
	PGOOD
);
	// _sv2v_0: added by the conversion. An always_comb block runs once at
	// time zero; always @(*) does not, so each converted block reads this
	// constant-zero register to be evaluated at start-up in simulation.
	// Never assigned after time zero; synthesis removes it.
	reg _sv2v_0;
	// Package constants used here, inlined by the conversion from
	// pmic_types_pkg.sv. Each is evaluated at elaboration; none is hardware.
	// PGOOD_DELAY_MS: time the rail must be continuously good in S_RUN
	//                 before PGOOD asserts and the secondary circuitry is
	//                 handed over from the input LDO
	localparam signed [31:0] pmic_types_pkg_PGOOD_DELAY_MS = 9;
	// CONVERTOR_HZ: switching frequency of the analog modulator
	localparam signed [31:0] pmic_types_pkg_CONVERTOR_HZ = 450000;
	// ms_to_sw_cycles: milliseconds -> switching cycles.
	function automatic signed [31:0] pmic_types_pkg_ms_to_sw_cycles;
		input reg signed [31:0] ms;
		pmic_types_pkg_ms_to_sw_cycles = 450 * ms;
	endfunction
	// PGOOD_DELAY_CYCLES: the same interval in switching cycles
	localparam signed [31:0] pmic_types_pkg_PGOOD_DELAY_CYCLES = pmic_types_pkg_ms_to_sw_cycles(pmic_types_pkg_PGOOD_DELAY_MS);
	// PGOOD_DELAY_CYCLES: switching cycles the rail must be continuously good
	//                     before PGOOD asserts. Overridden far below the
	//                     default in simulation.
	parameter signed [31:0] PGOOD_DELAY_CYCLES = pmic_types_pkg_PGOOD_DELAY_CYCLES;
	// PGOOD_DELAY_W: width of the qualifying counter, derived so a call-site
	//                override cannot truncate it
	parameter signed [31:0] PGOOD_DELAY_W = $clog2(PGOOD_DELAY_CYCLES + 1);
	input wire clk;
	input wire rst_n;
	input wire pwm_sync;  // synchronised raw PWM, for the cycle boundary
	input wire pgood_comp;  // synchronised output comparator, high when the rail is above threshold
	input wire run_active;  // high only while the supervisor is in S_RUN
	output reg PGOOD;  // power good, to the supply changeover and telemetry
	// pwm_sync_d: pwm_sync delayed one clk, used to detect the cycle boundary
	reg pwm_sync_d;
	// pwm_fall: one-clk pulse marking the end of a switching cycle
	reg pwm_fall;
	// qualify_counter: switching cycles the rail has been good while regulating
	reg [PGOOD_DELAY_W - 1:0] qualify_counter;
	// sv2v_cast_*: generated by the conversion. Each implements one
	// SystemVerilog width cast, N'(x), of the source: it returns its
	// argument resized to the declared width - a pure width conversion that adds no logic.
	function automatic signed [PGOOD_DELAY_W - 1:0] sv2v_cast_C6A89_signed;
		input reg signed [PGOOD_DELAY_W - 1:0] inp;
		sv2v_cast_C6A89_signed = inp;
	endfunction
	// TARGET: qualifying count the counter stops at and PGOOD qualifies against.
	//         Sized to the counter rather than left as int, so the assignment
	//         below is not a truncation. Taken from the parameter, not from the
	//         package, so a call-site override reaches both comparisons.
	localparam [PGOOD_DELAY_W - 1:0] TARGET = sv2v_cast_C6A89_signed(PGOOD_DELAY_CYCLES);
	/*
	Purpose:
	---
	Create a one-clock delayed copy of the synchronised PWM so that the end
	of a switching cycle can be detected combinationally below.
	*/
	always @(posedge clk or negedge rst_n)
		if (!rst_n)
			pwm_sync_d <= 0;
		else
			pwm_sync_d <= pwm_sync;
	/*
	Purpose:
	---
	One-clk enable pulse marking the switching-cycle boundary, so the
	qualifying counter below advances once per cycle rather than once per
	clock.
	*/
	always @(*) begin
		if (_sv2v_0)
			;
		pwm_fall = pwm_sync_d & ~pwm_sync;
	end
	/*
	Purpose:
	---
	Count switching cycles for which the rail has been continuously good
	while the supervisor is regulating, saturating at the terminal value
	rather than wrapping.

	Both run_active and pgood_comp appear in the clear condition, so the
	qualifying period measures *consecutive* good cycles: any dip below the
	comparator threshold, or any departure from S_RUN, restarts it from zero
	rather than resuming where it left off.

	pgood_comp arrives through an input_sync instance, so it changes only on
	clock edges. That matters here as well as for metastability: a transition
	the combinational output below reacts to cannot be shorter than one clock,
	so this counter can never miss a dip that PGOOD has already responded to.
	*/
	always @(posedge clk or negedge rst_n)
		if (!rst_n)
			qualify_counter <= 0;
		else if (!run_active || !pgood_comp)
			qualify_counter <= 0;
		else if (pwm_fall) begin
			if (qualify_counter == TARGET)
				qualify_counter <= TARGET;
			else
				qualify_counter <= qualify_counter + 1;
		end
	/*
	Purpose:
	---
	PGOOD is the saturated counter ANDed with the two live conditions, not a
	registered flag. The asymmetry is deliberate and is the whole point of
	the module: assertion is slow because qualify_counter must climb the full
	delay, while deassertion is immediate because pgood_comp and run_active
	appear directly in this expression and bypass the counter entirely.

	PGOOD drives the changeover that moves the secondary analog circuitry off
	the input LDO and onto the converter's own output. That load must be
	handed back to the LDO before the rail collapses, so a registered output -
	which would cost an extra clock and could disagree with the counter
	driving it - is the wrong choice here, unlike the gate-drive paths in
	pwm_mask and the supervisor where a combinational glitch would be a
	shoot-through hazard.
	*/
	always @(*) begin
		if (_sv2v_0)
			;
		PGOOD = ((qualify_counter == TARGET) & pgood_comp) & run_active;
	end
	initial _sv2v_0 = 0;
endmodule
`default_nettype wire
