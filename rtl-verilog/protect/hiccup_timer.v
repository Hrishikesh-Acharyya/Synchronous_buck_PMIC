/*

# Filename:         hiccup_timer.v

# File Description: Cool-down timer for the hiccup state. Holds the gate driver
                    off for a duration that doubles with each strike,
#                   so a fault that keeps recurring is given progressively
#                   longer to clear before the next retry. Asserts
#                   hiccup_done when the interval has elapsed, which is what
#                   releases the supervisor from S_HICCUP back to S_SS.

#                   Verilog-2005, converted from rtl/protect/hiccup_timer.sv by sv2v,
#                   with the comments restored by hand from the source.

# Global variables: None

*/
`timescale 1ns/1ps
`default_nettype none
module hiccup_timer (
	clk,
	rst_n,
	hiccup_active,
	strike_level,
	base_clks,
	hiccup_done
);
	// _sv2v_0: added by the conversion. An always_comb block runs once at
	// time zero; always @(*) does not, so each converted block reads this
	// constant-zero register to be evaluated at start-up in simulation.
	// Never assigned after time zero; synthesis removes it.
	reg _sv2v_0;
	// Package constants used here, inlined by the conversion from
	// pmic_types_pkg.sv. Each is evaluated at elaboration; none is hardware.
	// MAX_STRIKES_DEFAULT: hiccup retries permitted before latch_assert, and
	//                      the reset value of the writable max_strikes
	//                      register. Writable DOWNWARD ONLY: raising it would
	//                      allow more retries into a persistent fault, and
	//                      would also widen STRIKE_W and HICCUP_TIMER_W, so
	//                      reg_file saturates upward writes at this value.
	localparam signed [31:0] pmic_types_pkg_MAX_STRIKES_DEFAULT = 3;
	// STRIKE_W: width of the strike level bus, shared by strike_counter and
	//           hiccup_timer
	localparam signed [31:0] pmic_types_pkg_STRIKE_W = 2;
	// STRIKE_W: width of the strike level input
	parameter signed [31:0] STRIKE_W = pmic_types_pkg_STRIKE_W;
	// CLK_HZ: supervisor clock, from the external oscillator
	localparam signed [31:0] pmic_types_pkg_CLK_HZ = 50000000;
	// ms_to_clks: milliseconds -> clk counts
	function automatic signed [31:0] pmic_types_pkg_ms_to_clks;
		input reg signed [31:0] ms;
		pmic_types_pkg_ms_to_clks = 50000 * ms;
	endfunction
	localparam signed [31:0] pmic_types_pkg_HICCUP_BASE_MAX_CLKS = pmic_types_pkg_ms_to_clks(20);
	// HICCUP_TIMER_W: width of the cool-down counter. Sized for the longest
	//                 interval the host can command - HICCUP_BASE_MAX_CLKS
	//                 shifted by MAX_STRIKES_DEFAULT-1, not the default base.
	//                 Sizing this from the default would let a legal host
	//                 write overflow the counter and end the cool-down early.
	localparam signed [31:0] pmic_types_pkg_HICCUP_TIMER_W = $clog2((pmic_types_pkg_HICCUP_BASE_MAX_CLKS << 2) + 1);
	// TIMER_W: width of the cool-down counter, sized for the longest interval
	parameter signed [31:0] TIMER_W = pmic_types_pkg_HICCUP_TIMER_W;
	input wire clk;
	input wire rst_n;
	input wire hiccup_active;  // high only while the supervisor is in S_HICCUP
	input wire [STRIKE_W - 1:0] strike_level;  // strikes accumulated so far
	// HICCUP_BASE_W: width of the writable base register. Sized for the
	//                largest LEGAL base, not the default.
	localparam signed [31:0] pmic_types_pkg_HICCUP_BASE_W = $clog2(pmic_types_pkg_HICCUP_BASE_MAX_CLKS + 1);
	input wire [pmic_types_pkg_HICCUP_BASE_W - 1:0] base_clks;  // base_clks: cool-down for strike level 0
	output reg hiccup_done;  // cool-down interval has elapsed
	// cool_down_target: BASE_CLKS shifted left by strike_level
	reg [TIMER_W - 1:0] cool_down_target;
	// cool_counter: clk ticks elapsed in the present cool-down
	reg [TIMER_W - 1:0] cool_counter;
	// sv2v_cast_*: generated by the conversion. Each implements one
	// SystemVerilog width cast, N'(x), of the source: it returns its
	// argument resized to the declared width - a pure width conversion that adds no logic.
	function automatic [TIMER_W - 1:0] sv2v_cast_5FB0D;
		input reg [TIMER_W - 1:0] inp;
		sv2v_cast_5FB0D = inp;
	endfunction
	/*
	Purpose:
	---
	Derive the cool-down interval for the present strike level. Each strike
	doubles the interval, so a fault that keeps recurring is given
	progressively longer to clear.

	strike_counter increments on entry to S_HICCUP, one clock after
	hiccup_active rises, so cool_down_target steps up while cool_counter is
	still near zero. The match below simply occurs at the new, larger target;
	the target only ever grows, so the counter can never step past it.
	*/
	always @(*) begin
		if (_sv2v_0)
			;
		cool_down_target = sv2v_cast_5FB0D(base_clks) << strike_level;
	end
	/*
	Purpose:
	---
	Run the cool-down while the supervisor holds S_HICCUP, and assert
	hiccup_done once the interval has elapsed. The counter is held at target
	rather than reset, so a waveform distinguishes a finished cool-down from
	one that has just re-armed.

	Clocks are counted rather than switching cycles: the power stage is
	disabled throughout S_HICCUP, so there is no PWM and no cycle boundary
	to count.

	The !hiccup_active branch clears both the counter and hiccup_done on
	leaving the state. Without it hiccup_done would stay asserted into S_SS
	and S_RUN, and the next entry into S_HICCUP would exit immediately on the
	stale flag - skipping every cool-down after the first, which is exactly
	the case the escalating interval exists for.
	*/
	always @(posedge clk or negedge rst_n)
		if (!rst_n) begin
			cool_counter <= 0;
			hiccup_done <= 0;
		end
		else if (!hiccup_active) begin
			hiccup_done <= 1'b0;
			cool_counter <= 0;
		end
		else if (cool_counter == cool_down_target) begin
			hiccup_done <= 1'b1;
			cool_counter <= cool_counter;
		end
		else
			cool_counter <= cool_counter + 1;
	initial _sv2v_0 = 0;
endmodule
`default_nettype wire
